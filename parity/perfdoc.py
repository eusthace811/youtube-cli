"""Writes docs/PERF.md from each PR's perf evidence file."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TITLES = {
    "r0": "Corpus wall time (oracle harness)", "r1": "Startup, memory and binary size", "r2": "Decode and re-encode 500 videos",
    "r3": "Token load and client setup", "r4": "Paginated list of 4,000 videos", "r5": "100 sequential write commands",
    "r6": "2 GiB upload", "r7": "MCP initialize and tools/list", "r8": "HTTP MCP under 50 concurrent clients",
    "r9": "Agent loop, 50 tool calls", "r10": "Agent web launcher", "r11": "Download size per channel",
}


def main():
    lines = ["# Performance", "",
             "Each PR's probe compares the Rust head against the Go reference (trunk) on the same machine, interleaving runs and reporting medians, per the plan's Verify, perf blocks. Generated by `parity/perfdoc.py` from `docs/evidence/<pr>/<pr>-perf.txt`; R12 lane 7 reruns every probe at the final head.", ""]
    for n in range(13):
        pr = f"r{n}"
        f = ROOT / "docs/evidence" / pr / f"{pr}-perf.txt"
        if not f.exists():
            continue
        text = f.read_text().strip().splitlines()
        lines += [f"## {pr.upper()}: {TITLES.get(pr, '')}", "", f"Verdict: {text[0].split(': ', 1)[1]}", "", "```"] + text[2:] + ["```", ""]
    (ROOT / "docs/PERF.md").write_text("\n".join(lines))
    print("docs/PERF.md written")


if __name__ == "__main__":
    main()
