"""Writes docs/PARITY.md: the full corpus, the MCP contract and every help
text compared against the Go oracle, with one row per Appendix E
divergence. Exits 1 when any difference is not registered.

    python3 -I parity/report.py --bin target/release/youtube
"""
import argparse
import inspect
import json
import subprocess
import sys
import tomllib
from pathlib import Path

PARITY = Path(__file__).resolve().parent
ROOT = PARITY.parent
sys.path.insert(0, str(PARITY))
import diff as differ  # noqa: E402
import run as runner  # noqa: E402
from recorder import Recorder  # noqa: E402

KNOWN_GO_DEFECTS = [
    ("comment markAsSpam / setModerationStatus", "print the input struct itself, including \"confirmed\":false"),
    ("liveBroadcast bind", "prints the response id and an empty stream id when --streamId is unset"),
    ("agent skill toolset", "list_skills is empty and load_skill finds nothing, because youtube's embed nests the skill one directory deeper than ADK reads; `Skills::embedded()` in crates/youtube-agent is the ready fix"),
]

# Where Go would crash, the port fails safe instead. No corpus case can
# record a crash as Go's golden, so these are listed rather than compared.
GO_CRASHES_AVOIDED = [
    ("several list tables", "Go dereferences nil nested fields and would crash; the port prints empty cells (never reachable with real API responses)"),
    ("MCP tools/call with \"arguments\": null", "Go panics (\"assignment to entry in nil map\", exit 2, no reply); the port treats it as {}"),
]


def run_corpus(binary):
    cases = runner.load_cases()
    rec = Recorder()
    results = []
    for case in cases:
        head = runner.run_case(binary, case, rec)
        golden = json.loads((runner.GOLDEN / f"{case.get('golden_from', case['id'])}.json").read_text())
        results.append((case, differ.compare(golden, head, case)))
    rec.close()
    return results


def contract_and_help(binary):
    p = subprocess.run([sys.executable, "-I", str(PARITY / "contract.py"), "--bin", binary, "--compare", str(PARITY / "golden/mcp-contract.json"),
                        "--allow", "E1=$help.youtube caption download,E16=$help.youtube agent.stdout,E19=$help.youtube video insert.stdout,E19=$.tools.result.tools[66].inputSchema.properties.tags.default"], capture_output=True, text=True)
    unregistered = [l for l in p.stdout.splitlines() if l and not l.startswith(("registered", "contract:"))]
    registered = [l for l in p.stdout.splitlines() if l.startswith("registered")]
    return unregistered, registered


def build(results, unregistered_contract, registered_contract):
    divergences = tomllib.loads((PARITY / "divergences.toml").read_text())["divergence"]
    unexplained = [(c["id"], d) for c, ds in results for d in ds] + [("contract", d) for d in unregistered_contract]
    surfaces = {}
    for c, ds in results:
        s = c.get("surface", "cli")
        surfaces.setdefault(s, [0, 0])
        surfaces[s][0] += 1
        surfaces[s][1] += len(ds)
    by_id = {k: [c["id"] for c, _ in results if k in c.get("divergences", [])] for k in divergences}
    lines = ["# Parity with the Go reference", "",
             "Every case runs the Rust binary and compares it with what the Go reference (`eat-pray-ai/yutu@bbf38cb`, built by `ref/build.sh`) did for the same input: the HTTP requests it sent (method, path, query, body by value), stdout, stderr and the exit code, byte for byte after the normalizations below. Generated by `parity/report.py`.", "",
             "## Results", "", "| Surface | Cases | Unexplained differences |", "|---|---|---|"]
    for s, (n, d) in sorted(surfaces.items()):
        lines.append(f"| {s} | {n} | {d} |")
    lines += [f"| MCP contract and all {117} help texts | 1 | {len(unregistered_contract)} |", "",
              "## Normalizations", "", "Only these, each one function in `parity/diff.py`:", ""]
    for name in ("split_part", "mask_boundary", "multipart_parts", "body_value", "mask_time", "mask_port", "mcp_by_value", "rename_go", "drop_go_upload_tag"):
        lines.append(f"- `{name}`: {inspect.getdoc(getattr(differ, name))}")
    lines += ["", "## Registered divergences (Appendix E)", "", "| Id | Change | PRs | Corpus cases tagged | Proof |", "|---|---|---|---|---|"]
    for k in sorted(divergences, key=lambda x: int(x[1:])):
        d = divergences[k]
        lines.append(f"| {k} | {d['summary']} | {', '.join(d['prs'])} | {len(by_id[k])} | {d['proof']} |")
    if registered_contract:
        lines += ["", "Contract or help differences accepted under a registered id:", ""] + [f"- {l[:200]}" for l in registered_contract]
    lines += ["", "## Known Go defects reproduced on purpose", "", "Go is the oracle, so these behave as Go does. They are candidates for fixes after cutover.", ""]
    lines += [f"- **{a}**: {b}" for a, b in KNOWN_GO_DEFECTS]
    lines += ["", "## Go crashes the port avoids", ""] + [f"- **{a}**: {b}" for a, b in GO_CRASHES_AVOIDED]
    if unexplained:
        lines += ["", "## Unexplained differences", ""] + [f"- `{cid}`: {d[:300]}" for cid, d in unexplained]
    total = len(results) + 1
    lines += ["", f"cases: {total}, differences: {len(unexplained)}, divergences: {len(divergences)}, {'all registered' if not unexplained else 'NOT all registered'}", ""]
    return "\n".join(lines), unexplained


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin", required=True)
    ap.add_argument("--out", default=str(ROOT / "docs/PARITY.md"))
    a = ap.parse_args()
    binary = str(Path(a.bin).resolve())
    results = run_corpus(binary)
    unregistered, registered = contract_and_help(binary)
    text, unexplained = build(results, unregistered, registered)
    Path(a.out).write_text(text)
    print(text.splitlines()[-1])
    sys.exit(1 if unexplained else 0)


if __name__ == "__main__":
    main()
