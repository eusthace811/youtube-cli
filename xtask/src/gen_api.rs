//! Generates crates/yutu-api/src/generated.rs from spec/youtube-v3.json and
//! the Go struct layout in parity/golden/go-dump.json. The output is the type
//! table the codec walks and the method table the client builds requests from.

use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;

const PKG: &str = "google.golang.org/api/youtube/v3.";
const SERVER_RESPONSE: &str = "google.golang.org/api/googleapi.ServerResponse";

pub fn run(args: &[String]) -> Result<(), String> {
    let root = crate::repo_root();
    let spec: Value = serde_json::from_str(
        &fs::read_to_string(root.join("spec/youtube-v3.json")).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    let dump: Value = serde_json::from_str(
        &fs::read_to_string(root.join("parity/golden/go-dump.json")).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    let (text, methods, schemas) = generate(&spec, &dump)?;
    let path = root.join("crates/yutu-api/src/generated.rs");
    if args.iter().any(|a| a == "--check") {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current != text {
            return Err("generated.rs is stale: run `cargo run -p xtask -- gen-api`".into());
        }
        println!("generated.rs up to date ({methods} methods, {schemas} schemas)");
        return Ok(());
    }
    fs::write(&path, text).map_err(|e| e.to_string())?;
    println!("generated.rs written ({methods} methods, {schemas} schemas)");
    Ok(())
}

fn short(go_type: &str) -> String {
    go_type
        .trim_start_matches(PKG)
        .replace("google.golang.org/api/googleapi.", "")
}

fn const_name(name: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = name.chars().collect();
    for (i, c) in chars.iter().enumerate() {
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_lowercase());
        if i > 0
            && c.is_uppercase()
            && (chars[i - 1].is_lowercase() || chars[i - 1].is_ascii_digit() || next_lower)
        {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

fn generate(spec: &Value, dump: &Value) -> Result<(String, usize, usize), String> {
    let types: BTreeMap<String, &Value> = dump["types"]
        .as_array()
        .ok_or("dump has no types")?
        .iter()
        .map(|t| (short(t["name"].as_str().unwrap()), &t["fields"]))
        .collect();
    let ids: BTreeMap<&str, usize> = types
        .keys()
        .enumerate()
        .map(|(i, k)| (k.as_str(), i))
        .collect();
    let id = |t: &str| -> Result<usize, String> {
        ids.get(t)
            .copied()
            .ok_or_else(|| format!("unknown type {t}"))
    };

    let mut out = String::from(
        "// Code generated by `cargo run -p xtask -- gen-api` from spec/youtube-v3.json\n// and parity/golden/go-dump.json. DO NOT EDIT.\n\nuse crate::schema::{Field, Kind, Location, Method, Param, TypeDef};\n\n",
    );
    for (name, i) in &ids {
        writeln!(out, "pub const {}: usize = {i};", const_name(name)).unwrap();
    }
    writeln!(out, "\npub static TYPES: &[TypeDef] = &[").unwrap();
    for (name, fields) in &types {
        write!(out, "    TypeDef {{ name: {name:?}, fields: &[").unwrap();
        for f in fields.as_array().map(Vec::as_slice).unwrap_or_default() {
            let go = f["name"].as_str().unwrap();
            let tag = f["tag"].as_str().unwrap();
            let json_tag = tag
                .strip_prefix("json:\"")
                .and_then(|t| t.strip_suffix('"'))
                .unwrap_or("");
            let mut parts = json_tag.split(',');
            let json_name = parts.next().unwrap_or("");
            let opts: Vec<&str> = parts.collect();
            let ty = f["type"].as_str().unwrap();
            let kind = match ty {
                "string" => "Kind::String".to_string(),
                "bool" => "Kind::Bool".to_string(),
                "int" => "Kind::Int".to_string(),
                "int64" => "Kind::Int64".to_string(),
                "uint64" => "Kind::Uint64".to_string(),
                "float64" => "Kind::Float64".to_string(),
                "*int64" => "Kind::PtrInt64".to_string(),
                "*bool" => "Kind::PtrBool".to_string(),
                "[]string" => "Kind::Strings".to_string(),
                "map[string][]string" => "Kind::Header".to_string(),
                SERVER_RESPONSE => format!("Kind::Inline({})", id("ServerResponse")?),
                t if t.starts_with("*") => format!("Kind::Ptr({})", id(&short(&t[1..]))?),
                t if t.starts_with("[]*") => format!("Kind::PtrSlice({})", id(&short(&t[3..]))?),
                t if t.starts_with("map[string]") => {
                    format!("Kind::Map({})", id(&short(&t[11..]))?)
                }
                other => return Err(format!("unsupported Go type {other} in {name}.{go}")),
            };
            write!(
                out,
                "Field {{ go: {go:?}, json: {:?}, kind: {kind}, string: {}, omitempty: {}, skip: {} }}, ",
                if json_name == "-" { "" } else { json_name },
                opts.contains(&"string"),
                opts.contains(&"omitempty"),
                json_name == "-"
            )
            .unwrap();
        }
        writeln!(out, "] }},").unwrap();
    }
    writeln!(out, "];\n").unwrap();

    let mut methods = Vec::new();
    collect(&spec["resources"], &mut methods);
    methods.sort_by(|a, b| a["id"].as_str().cmp(&b["id"].as_str()));
    writeln!(out, "pub static METHODS: &[Method] = &[").unwrap();
    for m in &methods {
        let typ = |k: &str| -> Result<String, String> {
            Ok(match m[k]["$ref"].as_str() {
                Some(r) => format!("Some({})", id(r)?),
                None => "None".into(),
            })
        };
        let upload = m["mediaUpload"]["protocols"]["simple"]["path"]
            .as_str()
            .map(|p| format!("Some({:?})", p.trim_start_matches('/')))
            .unwrap_or_else(|| "None".into());
        write!(
            out,
            "    Method {{ id: {:?}, http_method: {:?}, path: {:?}, upload_path: {upload}, request: {}, response: {}, download: {}, params: &[",
            m["id"].as_str().unwrap(),
            m["httpMethod"].as_str().unwrap(),
            m.get("flatPath").unwrap_or(&m["path"]).as_str().unwrap(),
            typ("request")?,
            typ("response")?,
            m["supportsMediaDownload"].as_bool().unwrap_or(false),
        )
        .unwrap();
        let params: BTreeMap<&String, &Value> = m["parameters"]
            .as_object()
            .map(|p| p.iter().collect())
            .unwrap_or_default();
        for (pname, p) in params {
            write!(
                out,
                "Param {{ name: {pname:?}, location: Location::{}, repeated: {}, required: {} }}, ",
                if p["location"] == "path" {
                    "Path"
                } else {
                    "Query"
                },
                p["repeated"].as_bool().unwrap_or(false),
                p["required"].as_bool().unwrap_or(false)
            )
            .unwrap();
        }
        writeln!(out, "] }},").unwrap();
    }
    writeln!(out, "];").unwrap();
    let schemas = spec["schemas"].as_object().map(|s| s.len()).unwrap_or(0);
    for s in spec["schemas"].as_object().unwrap().keys() {
        id(s)?;
    }
    Ok((out, methods.len(), schemas))
}

fn collect(resources: &Value, out: &mut Vec<Value>) {
    for r in resources.as_object().into_iter().flat_map(|o| o.values()) {
        for m in r["methods"]
            .as_object()
            .into_iter()
            .flat_map(|o| o.values())
        {
            out.push(m.clone());
        }
        collect(&r["resources"], out);
    }
}
