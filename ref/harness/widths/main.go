// Command yutu-go-widths prints go-pretty's per-rune display widths as Rust
// range tables, for the table renderer in crates/youtube-core.
package main

import (
	"fmt"

	"github.com/mattn/go-runewidth"
)

func width(c *runewidth.Condition, r rune) int {
	if (r >= 0x2500 && r <= 0x257F) || (r >= 0x2580 && r <= 0x259F) {
		return 1
	}
	return c.RuneWidth(r)
}

func table(name string, eastAsian bool) {
	c := &runewidth.Condition{EastAsianWidth: eastAsian, StrictEmojiNeutral: true}
	fmt.Printf("pub static %s: &[(u32, u32, u8)] = &[\n", name)
	start, cur := rune(0), width(c, 0)
	for r := rune(1); r <= 0x110000; r++ {
		w := -1
		if r <= 0x10FFFF {
			w = width(c, r)
		}
		if w != cur {
			if cur != 1 {
				fmt.Printf("    (0x%X, 0x%X, %d),\n", start, r-1, cur)
			}
			start, cur = r, w
		}
	}
	fmt.Println("];")
}

func main() {
	fmt.Println("// Code generated by ref/harness/widths from github.com/mattn/go-runewidth v0.0.30\n// as used by go-pretty v6.8.3. DO NOT EDIT. Runes not listed have width 1.\n")
	table("NARROW", false)
	fmt.Println()
	table("EAST_ASIAN", true)
}
